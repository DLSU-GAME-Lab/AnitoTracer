#pragma once

#include "Graphics/GraphicsEngine/interface/RenderDevice.h"
#include "Graphics/GraphicsEngine/interface/DeviceContext.h"
#include "Graphics/GraphicsTools/interface/MapHelper.hpp"
#include "Common/interface/RefCntAutoPtr.hpp"

// Small helpers shared by every pipeline, so pipelines only describe what is specific to them
namespace Diligent::PipelineUtils {

    // Sample count that MSAA-aware PSOs and targets must use, from UserSettings
    Uint8 GetMSAASampleCount();

    // Dynamic, CPU-writable uniform buffer
    RefCntAutoPtr<IBuffer> CreateDynamicCB(IRenderDevice* pDevice, const char* name, Uint64 size);

    template <typename T>
    RefCntAutoPtr<IBuffer> CreateDynamicCB(IRenderDevice* pDevice, const char* name) {
        return CreateDynamicCB(pDevice, name, sizeof(T));
    }

    // Uploads one struct into a dynamic buffer, discarding its previous contents
    template <typename T>
    void WriteCB(IDeviceContext* pContext, IBuffer* pBuffer, const T& data) {
        MapHelper<T> CBData(pContext, pBuffer, MAP_WRITE, MAP_FLAG_DISCARD);
        *CBData = data;
    }

    // Returns an SRB with static resources initialized, or nullptr if pPSO is null
    RefCntAutoPtr<IShaderResourceBinding> CreateSRB(IPipelineState* pPSO);

    // Sets a variable only if the shader declares it (compilers strip unused resources), so it is safe to call for optional ones
    void BindVariable(IShaderResourceBinding* pSRB, SHADER_TYPE shaderType, const char* name, IDeviceObject* pObject,
        SET_SHADER_RESOURCE_FLAGS flags = SET_SHADER_RESOURCE_FLAG_NONE);

    SamplerDesc LinearWrapSampler();
    SamplerDesc LinearClampSampler();
    SamplerDesc PointClampSampler();

    // 1x1 immutable texture (or cube with 6 identical faces) filled with a packed RGBA8 color, e.g. 0xFF000000 for opaque black
    RefCntAutoPtr<ITexture> CreateSolidColorTexture(IRenderDevice* pDevice, const char* name, Uint32 rgba, bool cube = false);

    // Viewport of the given size anchored at the top-left of a render target that may be larger
    void SetViewport(IDeviceContext* pContext, Uint32 width, Uint32 height, Uint32 targetWidth, Uint32 targetHeight);

    // Draws the 3-vertex triangle generated by Shaders/Deferred/fullscreen_vs.hlsl
    void DrawFullscreenTriangle(IDeviceContext* pContext);

}
